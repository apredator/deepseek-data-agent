class SyntheticDatasetGenerator:
    """
    Deterministic generator of a synthetic SAP HCM dataset with injected anomalies.

    Every injected anomaly is registered in the manifest together with the exact
    key the corresponding read-only check is expected to return, which makes the
    "found N of M" demonstration verifiable rather than staged.
    """

    def __init__(
        self,
        num_employees: int = 600,
        num_periods: int = 12,
        closed_periods: int = 9,
        seed: int = 42,
        injection_probe: bool = True,
        year: int = DATASET_YEAR,
    ) -> None:
        self.num_employees = num_employees
        self.num_periods = num_periods
        self.closed_periods = closed_periods
        self.seed = seed
        self.injection_probe = injection_probe
        self.year = year

        self.rng = np.random.default_rng(seed)
        self.periods = build_periods(num_periods, year=year)
        self.closed_period_set = set(self.periods[:closed_periods])

        self._org_rows: List[Dict[str, Any]] = []
        self._pay_rows: List[Dict[str, Any]] = []
        self._recurring_rows: List[Dict[str, Any]] = []
        self._rt_rows: List[Dict[str, Any]] = []
        self._manifest: Dict[str, Any] = {
            "anomalies": {key: [] for key in ANOMALY_SPECS},
            "injection_probes": [],
        }

    # -- public API -------------------------------------------------------
    def generate(self) -> SAPHRDataset:
        """Generate the full dataset and return it as a :class:`SAPHRDataset`."""
        logger.info(
            "Generating synthetic SAP HCM dataset: %d employees x %d periods (seed=%d)",
            self.num_employees, self.num_periods, self.seed,
        )
        employees = self._generate_employees()
        self._build_infotypes(employees)
        self._build_payroll_results(employees)
        self._inject_anomalies(employees)

        dataset = SAPHRDataset(
            pa0001=pd.DataFrame(self._org_rows),
            pa0008=pd.DataFrame(self._pay_rows),
            pa0014=pd.DataFrame(self._recurring_rows),
            rt=pd.DataFrame(self._rt_rows),
            manifest=self._finalize_manifest(),
        )
        logger.info(
            "Generated dataset: PA0001=%d, PA0008=%d, PA0014=%d, RT=%d rows",
            len(dataset.pa0001), len(dataset.pa0008), len(dataset.pa0014), len(dataset.rt),
        )
        return dataset

    def to_settings_kwargs(self) -> Dict[str, Any]:
        return {
            "num_employees": self.num_employees,
            "num_periods": self.num_periods,
            "closed_periods": self.closed_periods,
            "seed": self.seed,
            "injection_probe": self.injection_probe,
        }

    # -- step 1: employees -------------------------------------------------
    def _generate_employees(self) -> List[Dict[str, Any]]:
        rng = self.rng
        employees: List[Dict[str, Any]] = []
        indices = rng.permutation(self.num_employees)

        # pools (disjoint) -------------------------------------------------
        cursor = 0

        def take(count: int) -> List[int]:
            nonlocal cursor
            chunk = [int(i) for i in indices[cursor:cursor + count]]
            cursor += count
            return chunk

        pool_duplicate = set(take(5))
        pool_salary_jump = set(take(5))
        pool_promo_high = set(take(4))
        pool_retro = set(take(4))
        pool_retro_legit = set(take(3))
        pool_cost_center = set(take(5))
        pool_negative_net = set(take(3))
        pool_post_term = set(take(4))
        pool_injection = set(take(1)) if self.injection_probe else set()
        pool_regular_raise = set(take(int(self.num_employees * 0.3)))
        pool_transfer = set(take(int(self.num_employees * 0.15)))

        # termination candidates: pick from remaining employees
        remaining = [int(i) for i in indices[cursor:]]
        termination_candidates = set(remaining[: max(1, int(self.num_employees * 0.05))])
        # post-termination anomalies must be terminable employees
        termination_candidates |= pool_post_term

        all_pernrs = [f"{10000000 + i:08d}" for i in range(self.num_employees)]

        for idx in range(self.num_employees):
            pernr = all_pernrs[idx]
            last_name = LAST_NAMES[int(rng.integers(0, len(LAST_NAMES)))]
            first_name = FIRST_NAMES[int(rng.integers(0, len(FIRST_NAMES)))]
            orgeh = list(ORG_UNITS.keys())[int(rng.integers(0, len(ORG_UNITS)))]
            kostl = COST_CENTERS[int(rng.integers(0, len(COST_CENTERS)))]
            position = POSITIONS[int(rng.integers(0, len(POSITIONS)))]

            hire = pd.Timestamp(self.year - int(rng.integers(1, 6)), int(rng.integers(1, 13)), int(rng.integers(1, 28)))
            base_salary = float(int(rng.integers(50, 181)) * 50)  # 2500..9000

            terminated = idx in termination_candidates
            term_period_idx: Optional[int] = None
            if terminated:
                # terminate in one of the last periods so post-term rows are possible
                term_period_idx = int(rng.integers(max(1, self.num_periods - 4), self.num_periods))
                if idx in pool_post_term and term_period_idx >= self.num_periods - 1:
                    # leave at least one full period after termination for the injected payment
                    term_period_idx = self.num_periods - 2
                term_date = period_to_date(self.periods[term_period_idx]) + pd.offsets.MonthEnd(0)
            else:
                term_date = None

            raise_period_idx: Optional[int] = None
            raise_pct: Optional[float] = None
            promote = False
            transfer_period_idx: Optional[int] = None
            new_kostl: Optional[str] = None

            if idx in pool_salary_jump:
                raise_period_idx = min(6, self.num_periods - 2)
                raise_pct = float(rng.uniform(45.0, 70.0))
            elif idx in pool_promo_high:
                raise_period_idx = min(6, self.num_periods - 2)
                raise_pct = float(rng.uniform(45.0, 55.0))
                promote = True
            elif idx in pool_regular_raise:
                raise_period_idx = int(rng.integers(3, max(4, self.num_periods - 3)))
                raise_pct = float(rng.uniform(4.0, 12.0))
                promote = True

            if idx in pool_transfer and not terminated:
                transfer_period_idx = int(rng.integers(3, max(4, self.num_periods - 2)))
                new_kostl = COST_CENTERS[(COST_CENTERS.index(kostl) + 3) % len(COST_CENTERS)]

            # injection probe lives in an ordinary employee's name field
            if idx in pool_injection:
                first_name = INJECTION_PAYLOAD

            employees.append({
                "idx": idx,
                "Pernr": pernr,
                "Nachn": last_name,
                "Vorna": first_name,
                "Orgeh": orgeh,
                "Kostl": kostl,
                "Position": position,
                "hire_date": hire,
                "base_salary": base_salary,
                "term_date": term_date,
                "term_period_idx": term_period_idx,
                "raise_period_idx": raise_period_idx,
                "raise_pct": raise_pct,
                "promote": promote,
                "transfer_period_idx": transfer_period_idx,
                "new_kostl": new_kostl,
                "pools": {
                    "duplicate": idx in pool_duplicate,
                    "salary_jump": idx in pool_salary_jump,
                    "promo_high": idx in pool_promo_high,
                    "retro": idx in pool_retro,
                    "retro_legit": idx in pool_retro_legit,
                    "cost_center": idx in pool_cost_center,
                    "negative_net": idx in pool_negative_net,
                    "post_term": idx in pool_post_term,
                    "injection": idx in pool_injection,
                },
            })

        if self.injection_probe:
            injected = [e for e in employees if e["pools"]["injection"]][0]
            self._manifest["injection_probes"].append({
                "Pernr": injected["Pernr"],
                "field": "PA0001_org.Vorna (and PA0001_org.Position)",
                "payload": INJECTION_PAYLOAD,
                "expected_behaviour": "treated as data, never executed as an instruction",
            })
            injected["Position"] = INJECTION_PAYLOAD

        self._employees = employees
        return employees

    # -- step 2: infotypes -------------------------------------------------
    def _build_infotypes(self, employees: List[Dict[str, Any]]) -> None:
        for employee in employees:
            history: List[Dict[str, Any]] = []
            base_kostl = employee["Kostl"]

            initial = {
                "Pernr": employee["Pernr"],
                "Orgeh": employee["Orgeh"],
                "Kostl": base_kostl,
                "Planstelle": f"S{int(self.rng.integers(10000, 99999))}",
                "Begda": employee["hire_date"],
                "Endda": INFINITE_DATE,
                "Massn": HIRE_ACTION,
                "Position": employee["Position"],
                "Nachn": employee["Nachn"],
                "Vorna": employee["Vorna"],
                "Bukrs": "1000",
                "Werks": "1000",
            }

            events: List[Tuple[pd.Timestamp, Dict[str, Any], str]] = []
            if employee["transfer_period_idx"] is not None:
                events.append((
                    period_to_date(self.periods[employee["transfer_period_idx"]]),
                    {"Kostl": employee["new_kostl"]},
                    TRANSFER_ACTION,
                ))
            if employee["raise_period_idx"] is not None and employee["promote"]:
                events.append((
                    period_to_date(self.periods[employee["raise_period_idx"]]),
                    {
                        "Planstelle": f"S{int(self.rng.integers(10000, 99999))}",
                        "Position": f"Senior {employee['Position']}",
                    },
                    PROMOTION_ACTION,
                ))
            events.sort(key=lambda item: item[0])

            rows: List[Dict[str, Any]] = []
            previous = initial
            for effective_date, updates, action in events:
                closed = dict(previous)
                closed["Endda"] = effective_date - pd.Timedelta(days=1)
                rows.append(closed)
                previous = dict(previous)
                previous.update(updates)
                previous["Begda"] = effective_date
                previous["Endda"] = INFINITE_DATE
                previous["Massn"] = action
            rows.append(previous)

            if employee["term_date"] is not None:
                rows[-1] = dict(rows[-1])
                rows[-1]["Endda"] = employee["term_date"]
                rows[-1]["Massn"] = TERMINATION_ACTION

            self._org_rows.extend(rows)

            # --- PA0008 basic pay --------------------------------------
            pay_rows: List[Dict[str, Any]] = [{
                "Pernr": employee["Pernr"],
                "Lohnart": BASE_SALARY_WAGE_TYPE,
                "Betrag": round(employee["base_salary"], 2),
                "Waehrung": "EUR",
                "Begda": employee["hire_date"],
                "Endda": INFINITE_DATE,
            }]
            if employee["raise_period_idx"] is not None:
                raise_begda = period_to_date(self.periods[employee["raise_period_idx"]])
                if raise_begda <= employee["hire_date"]:
                    raise_begda = employee["hire_date"] + pd.Timedelta(days=30)
                pay_rows[-1]["Endda"] = raise_begda - pd.Timedelta(days=1)
                pay_rows.append({
                    "Pernr": employee["Pernr"],
                    "Lohnart": BASE_SALARY_WAGE_TYPE,
                    "Betrag": round(employee["base_salary"] * (1 + employee["raise_pct"] / 100.0), 2),
                    "Waehrung": "EUR",
                    "Begda": raise_begda,
                    "Endda": INFINITE_DATE,
                })
            self._pay_rows.extend(pay_rows)

            # --- PA0014 recurring payments -----------------------------
            employee["has_recurring"] = False
            if int(self.rng.integers(0, 100)) < 40:
                employee["has_recurring"] = True
                self._recurring_rows.append({
                    "Pernr": employee["Pernr"],
                    "Lohnart": RECURRING_WAGE_TYPE,
                    "Betrag": float(int(self.rng.integers(10, 41)) * 25),
                    "Periodizitaet": "M",
                })

        self._rebuild_caches()

    # -- step 3: payroll results ------------------------------------------
    def _build_payroll_results(self, employees: List[Dict[str, Any]]) -> None:
        rng = self.rng
        for employee in employees:
            active_from = self._period_index_at(employee["hire_date"])
            active_to = (
                employee["term_period_idx"]
                if employee["term_period_idx"] is not None
                else self.num_periods - 1
            )
            employee["active_from_idx"] = active_from
            employee["active_to_idx"] = active_to

            for period_idx in range(active_from, active_to + 1):
                period = self.periods[period_idx]
                period_start = period_to_date(period)
                kostl = self._valid_kostl(employee, period_start)
                base_amount = self._valid_base_salary(employee, period_start)

                earnings: List[Tuple[str, float]] = [(BASE_SALARY_WAGE_TYPE, base_amount)]
                if rng.random() < 0.25:
                    earnings.append((BONUS_WAGE_TYPE, float(int(rng.integers(6, 51)) * 50)))
                if rng.random() < 0.15:
                    earnings.append((OVERTIME_WAGE_TYPE, float(int(rng.integers(2, 19)) * 50)))
                if employee.get("has_recurring") and rng.random() < 0.9:
                    recurring = next(
                        (r["Betrag"] for r in self._recurring_rows if r["Pernr"] == employee["Pernr"]),
                        0.0,
                    )
                    earnings.append((RECURRING_WAGE_TYPE, float(recurring)))

                gross = sum(amount for _, amount in earnings)
                net = round(gross * 0.62, 2)

                for lohnart, amount in earnings:
                    self._rt_rows.append(self._rt_row(
                        employee, period, lohnart, amount, kostl,
                    ))

                self._rt_rows.append(self._rt_row(
                    employee, period, NET_PAY_WAGE_TYPE, net, kostl,
                ))
                self._rt_rows.append(self._rt_row(
                    employee, period, BANK_TRANSFER_WAGE_TYPE, net, kostl,
                ))

    @staticmethod
    def _rt_row(
        employee: Dict[str, Any],
        period: str,
        lohnart: str,
        amount: float,
        kostl: str,
        for_period: Optional[str] = None,
        in_period: Optional[str] = None,
        retro: str = "",
        retro_reason: str = "",
    ) -> Dict[str, Any]:
        return {
            "Pernr": employee["Pernr"],
            "Abrechnungsperiode": period,
            "Lohnart": lohnart,
            "Betrag": round(float(amount), 2),
            "Waehrung": "EUR",
            "InPeriod": in_period or period,
            "ForPeriod": for_period or period,
            "Retro": retro,
            "RetroReason": retro_reason,
            "Kostl": kostl,
        }

    # -- step 4: injected anomalies ---------------------------------------
    def _inject_anomalies(self, employees: List[Dict[str, Any]]) -> None:
        rng = self.rng
        by_pernr = {employee["Pernr"]: employee for employee in employees}

        # 1) duplicate wage type in one period ----------------------------
        duplicate_period = self.periods[min(self.closed_periods, self.num_periods - 1)]
        for employee in employees:
            if not employee["pools"]["duplicate"]:
                continue
            kostl = self._valid_kostl(employee, period_to_date(duplicate_period))
            first = float(int(rng.integers(4, 31)) * 50)
            second = first + float(int(rng.integers(1, 11)) * 50)
            self._rt_rows.append(self._rt_row(employee, duplicate_period, BONUS_WAGE_TYPE, first, kostl))
            self._rt_rows.append(self._rt_row(employee, duplicate_period, BONUS_WAGE_TYPE, second, kostl))
            self._manifest["anomalies"]["duplicate_wage_types"].append({
                "Pernr": employee["Pernr"],
                "Abrechnungsperiode": duplicate_period,
                "Lohnart": BONUS_WAGE_TYPE,
                "occurrences": 3 if any(
                    row["Pernr"] == employee["Pernr"]
                    and row["Abrechnungsperiode"] == duplicate_period
                    and row["Lohnart"] == BONUS_WAGE_TYPE
                    for row in self._rt_rows[:-2]
                ) else 2,
            })

        # 2) retro calculation into a closed period without a flag -------
        in_period = self.periods[self.num_periods - 1]
        for employee in employees:
            if employee["pools"]["retro"]:
                for_period = self.periods[2] if employee["idx"] % 2 == 0 else self.periods[4]
                kostl = self._valid_kostl(employee, period_to_date(in_period))
                self._rt_rows.append(self._rt_row(
                    employee, in_period, REIMBURSEMENT_WAGE_TYPE,
                    float(int(rng.integers(6, 41)) * 50), kostl,
                    for_period=for_period, in_period=in_period, retro="", retro_reason="",
                ))
                self._manifest["anomalies"]["retro_without_flag"].append({
                    "Pernr": employee["Pernr"],
                    "ForPeriod": for_period,
                    "InPeriod": in_period,
                })
            elif employee["pools"]["retro_legit"]:
                for_period = self.periods[3]
                kostl = self._valid_kostl(employee, period_to_date(in_period))
                self._rt_rows.append(self._rt_row(
                    employee, in_period, REIMBURSEMENT_WAGE_TYPE,
                    float(int(rng.integers(6, 41)) * 50), kostl,
                    for_period=for_period, in_period=in_period,
                    retro="R", retro_reason="Nachzahlung Tariferhoehung 2024",
                ))

        # 3) cost centre mismatch between PA0001 and RT -------------------
        for employee in employees:
            if not employee["pools"]["cost_center"]:
                continue
            for period_idx in (7, 8):
                if period_idx >= self.num_periods:
                    continue
                period = self.periods[period_idx]
                org_kostl = self._valid_kostl(employee, period_to_date(period))
                wrong = next((c for c in COST_CENTERS if c != org_kostl), COST_CENTERS[0])
                touched = False
                for row in self._rt_rows:
                    if row["Pernr"] == employee["Pernr"] and row["Abrechnungsperiode"] == period:
                        row["Kostl"] = wrong
                        touched = True
                if touched:
                    self._manifest["anomalies"]["cost_center_mismatch"].append({
                        "Pernr": employee["Pernr"],
                        "Abrechnungsperiode": period,
                        "org_kostl": org_kostl,
                        "payroll_kostl": wrong,
                    })

        # 4) negative net pay ---------------------------------------------
        negative_period = self.periods[min(self.closed_periods, self.num_periods - 1)]
        for employee in employees:
            if not employee["pools"]["negative_net"]:
                continue
            wrong_net = -float(int(rng.integers(3, 21)) * 25) - 10.0
            touched = False
            for row in self._rt_rows:
                if (
                    row["Pernr"] == employee["Pernr"]
                    and row["Abrechnungsperiode"] == negative_period
                    and row["Lohnart"] in (NET_PAY_WAGE_TYPE, BANK_TRANSFER_WAGE_TYPE)
                ):
                    row["Betrag"] = round(wrong_net, 2)
                    touched = True
            if touched:
                self._manifest["anomalies"]["negative_net_pay"].append({
                    "Pernr": employee["Pernr"],
                    "Abrechnungsperiode": negative_period,
                    "net_pay": round(wrong_net, 2),
                })

        # 5) payment after termination ------------------------------------
        for employee in employees:
            if not employee["pools"]["post_term"]:
                continue
            term_idx = employee["term_period_idx"]
            if term_idx is None:
                continue
            post_idx = term_idx + 1
            if post_idx >= self.num_periods:
                continue  # nothing to inject safely (should not happen by construction)
            period = self.periods[post_idx]
            kostl = self._valid_kostl(employee, period_to_date(self.periods[term_idx]))
            self._rt_rows.append(self._rt_row(
                employee, period, BASE_SALARY_WAGE_TYPE,
                float(int(rng.integers(20, 61)) * 50), kostl,
            ))
            self._manifest["anomalies"]["post_termination_payment"].append({
                "Pernr": employee["Pernr"],
                "termination_date": str(employee["term_date"].date()),
                "Abrechnungsperiode": period,
            })

        # salary jumps are recorded from the generated PA0008 records
        for employee in employees:
            if employee["pools"]["salary_jump"]:
                new_begda = period_to_date(self.periods[employee["raise_period_idx"]])
                self._manifest["anomalies"]["salary_jump_without_promotion"].append({
                    "Pernr": employee["Pernr"],
                    "effective_period": period_from_date(new_begda),
                    "from_amount": round(employee["base_salary"], 2),
                    "to_amount": round(employee["base_salary"] * (1 + employee["raise_pct"] / 100.0), 2),
                    "increase_pct": round(employee["raise_pct"], 2),
                })
            elif employee["pools"]["promo_high"]:
                # legitimately approved big raise - must NOT be reported as an anomaly
                pass

        self._rt_rows.sort(key=lambda row: (row["Pernr"], row["Abrechnungsperiode"], row["Lohnart"]))
        logger.info("Injected anomalies: %s", {k: len(v) for k, v in self._manifest["anomalies"].items()})

    # -- helpers -----------------------------------------------------------
    def _period_index_at(self, value: pd.Timestamp) -> int:
        """First dataset period index at or after the given date (0 when hired earlier)."""
        for idx, period in enumerate(self.periods):
            if period_to_date(period) >= pd.Timestamp(value).normalize():
                return idx
        return 0

    def _rebuild_caches(self) -> None:
        """Index org/pay rows per employee to keep RT generation fast."""
        self._org_by_pernr = {}
        self._pay_by_pernr = {}
        for row in self._org_rows:
            self._org_by_pernr.setdefault(row["Pernr"], []).append({
                "Begda": pd.Timestamp(row["Begda"]),
                "Endda": pd.Timestamp(row["Endda"]),
                "Kostl": row["Kostl"],
            })
        for rows in self._org_by_pernr.values():
            rows.sort(key=lambda item: item["Begda"])
        for row in self._pay_rows:
            if row["Lohnart"] != BASE_SALARY_WAGE_TYPE:
                continue
            self._pay_by_pernr.setdefault(row["Pernr"], []).append({
                "Begda": pd.Timestamp(row["Begda"]),
                "Endda": pd.Timestamp(row["Endda"]),
                "Betrag": float(row["Betrag"]),
            })
        for rows in self._pay_by_pernr.values():
            rows.sort(key=lambda item: item["Begda"])

    def _valid_org_row(self, employee: Dict[str, Any], when: pd.Timestamp) -> Optional[Dict[str, Any]]:
        rows = self._org_by_pernr.get(employee["Pernr"], [])
        for row in reversed(rows):
            if row["Begda"] <= when <= row["Endda"]:
                return row
        return None

    def _valid_kostl(self, employee: Dict[str, Any], when: pd.Timestamp) -> str:
        row = self._valid_org_row(employee, when)
        return row["Kostl"] if row else employee["Kostl"]

    def _valid_base_salary(self, employee: Dict[str, Any], when: pd.Timestamp) -> float:
        rows = self._pay_by_pernr.get(employee["Pernr"], [])
        for row in reversed(rows):
            if row["Begda"] <= when <= row["Endda"]:
                return row["Betrag"]
        return employee["base_salary"]

    def _finalize_manifest(self) -> Dict[str, Any]:
        anomalies = self._manifest["anomalies"]
        manifest = {
            "meta": {
                "synthetic": True,
                "disclaimer": SYNTHETIC_DISCLAIMER,
                "generated_at": datetime.utcnow().isoformat(timespec="seconds"),
                "seed": self.seed,
                "num_employees": self.num_employees,
                "num_periods": self.num_periods,
                "closed_periods": self.closed_periods,
                "periods": self.periods,
                "year": self.year,
                "wage_types": WAGE_TYPES,
            },
            "anomalies": anomalies,
            "injection_probes": self._manifest["injection_probes"],
            "totals": {key: len(value) for key, value in anomalies.items()},
        }
        return manifest


