def generate_dataset(
    num_employees: Optional[int] = None,
    num_periods: Optional[int] = None,
    closed_periods: Optional[int] = None,
    seed: Optional[int] = None,
    injection_probe: Optional[bool] = None,
    settings: Optional[Settings] = None,
) -> SAPHRDataset:
    """Generate a dataset using explicit arguments or the configured defaults."""
    settings = settings or get_settings()
    generator = SyntheticDatasetGenerator(
        num_employees=num_employees if num_employees is not None else settings.num_employees,
        num_periods=num_periods if num_periods is not None else settings.num_periods,
        closed_periods=closed_periods if closed_periods is not None else settings.closed_periods,
        seed=seed if seed is not None else settings.seed,
        injection_probe=injection_probe if injection_probe is not None else settings.injection_probe,
    )
    return generator.generate()


def load_or_generate(data_dir: Path | str, settings: Optional[Settings] = None) -> SAPHRDataset:
    """Load the dataset from ``data_dir``, generating it on first use."""
    data_dir = Path(data_dir)
    try:
        return SAPHRDataset.load(data_dir)
    except FileNotFoundError:
        logger.info("No dataset found in %s - generating a fresh synthetic one", data_dir)
        dataset = generate_dataset(settings=settings)
        dataset.save(data_dir)
        return dataset


