def coerce_code_columns(dataset: "SAPHRDataset") -> "SAPHRDataset":
    """Normalize SAP coded fields (Pernr, Lohnart, Kostl, periods...) to strings."""
    for attribute, columns in CODE_COLUMNS.items():
        frame = getattr(dataset, attribute, None)
        if frame is None:
            continue
        for column in columns:
            if column in frame.columns:
                frame[column] = frame[column].astype(str)
    return dataset



