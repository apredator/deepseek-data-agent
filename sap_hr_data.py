@dataclass
class SAPHRDataset:
    """A loaded set of synthetic SAP HCM tables plus their ground-truth manifest."""

    pa0001: pd.DataFrame
    pa0008: pd.DataFrame
    pa0014: pd.DataFrame
    rt: pd.DataFrame
    manifest: Dict[str, Any] = field(default_factory=dict)
    data_dir: Optional[Path] = None

    # -- convenience ------------------------------------------------------
    @property
    def tables(self) -> Dict[str, pd.DataFrame]:
        return {
            "PA0001_org": self.pa0001,
            "PA0008_basic_pay": self.pa0008,
            "PA0014_recurring": self.pa0014,
            "RT_payroll_results": self.rt,
        }

    @property
    def num_employees(self) -> int:
        return int(self.pa0001["Pernr"].nunique()) if not self.pa0001.empty else 0

    def periods(self) -> List[str]:
        """Return the sorted list of payroll periods present in RT."""
        if self.rt.empty:
            return []
        return sorted(self.rt["Abrechnungsperiode"].astype(str).unique().tolist())

    def summary(self) -> Dict[str, Any]:
        """Compact, JSON-serializable overview used by the agent's system prompt."""
        return {
            "synthetic": True,
            "num_employees": self.num_employees,
            "periods": self.periods(),
            "tables": {
                name: {
                    "rows": int(df.shape[0]),
                    "columns": list(df.columns),
                }
                for name, df in self.tables.items()
            },
            "wage_types": WAGE_TYPES,
            "closed_periods": self.manifest.get("meta", {}).get("closed_periods"),
            "injected_anomaly_types": sorted(self.manifest.get("anomalies", {}).keys()),
        }

    def ground_truth(self) -> Dict[str, Set[Tuple[Any, ...]]]:
        """Return the injected anomalies as comparable key sets."""
        result: Dict[str, Set[Tuple[Any, ...]]] = {}
        anomalies = self.manifest.get("anomalies", {})
        for anomaly_type, (_, key_columns) in ANOMALY_SPECS.items():
            keys: Set[Tuple[Any, ...]] = set()
            for entry in anomalies.get(anomaly_type, []):
                keys.add(tuple(entry.get(col) for col in key_columns))
            result[anomaly_type] = keys
        return result

    # -- persistence ------------------------------------------------------
    def save(self, data_dir: Path | str) -> Path:
        """Write all tables, the manifest and the synthetic-data disclaimer to disk."""
        data_dir = Path(data_dir)
        data_dir.mkdir(parents=True, exist_ok=True)

        for attr, filename in TABLE_FILES.items():
            frame: pd.DataFrame = getattr(self, attr)
            frame.to_csv(data_dir / filename, index=False)

        manifest = dict(self.manifest)
        manifest.setdefault("meta", {})
        manifest["meta"]["saved_at"] = datetime.utcnow().isoformat(timespec="seconds")
        manifest["meta"]["synthetic"] = True

        with open(data_dir / MANIFEST_FILE, "w", encoding="utf-8") as handle:
            json.dump(manifest, handle, indent=2, ensure_ascii=False, default=str)

        (data_dir / DISCLAIMER_FILE).write_text(SYNTHETIC_DISCLAIMER + "\n", encoding="utf-8")

        self.data_dir = data_dir
        logger.info("Synthetic SAP HCM dataset saved to %s", data_dir)
        return data_dir

    @classmethod
    def load(cls, data_dir: Path | str, manifest: Optional[Dict[str, Any]] = None) -> "SAPHRDataset":
        """Load a previously generated dataset from disk."""
        data_dir = Path(data_dir)
        missing = [f for f in TABLE_FILES.values() if not (data_dir / f).exists()]
        if missing:
            raise FileNotFoundError(
                f"Dataset directory {data_dir} is incomplete, missing: {', '.join(missing)}. "
                "Run 'python generate_synthetic_dataset.py' first."
            )

        frames = {
            attr: pd.read_csv(data_dir / filename)
            for attr, filename in TABLE_FILES.items()
        }

        for column in ("Begda", "Endda"):
            for attr in ("pa0001", "pa0008"):
                if column in frames[attr].columns:
                    frames[attr][column] = pd.to_datetime(frames[attr][column], errors="coerce")

        if manifest is None:
            manifest_path = data_dir / MANIFEST_FILE
            if manifest_path.exists():
                with open(manifest_path, encoding="utf-8") as handle:
                    manifest = json.load(handle)

        dataset = cls(
            pa0001=frames["pa0001"],
            pa0008=frames["pa0008"],
            pa0014=frames["pa0014"],
            rt=frames["rt"],
            manifest=manifest or {},
            data_dir=data_dir,
        )
        return coerce_code_columns(dataset)


