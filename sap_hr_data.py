def build_periods(num_periods: int, year: int = DATASET_YEAR) -> List[str]:
    """Return a list of payroll periods such as ``['2024P01', ..., '2024P12']``."""
    return [f"{year}P{month:02d}" for month in range(1, num_periods + 1)]


def period_to_date(period: str) -> pd.Timestamp:
    """Convert ``'2024P07'`` into the first day of that payroll period."""
    normalized = normalize_period(period)
    year = int(normalized[:4])
    month = int(normalized[5:7])
    return pd.Timestamp(year=year, month=month, day=1)


def period_from_date(value: Any) -> str:
    """Convert a date-like value into a payroll period string."""
    ts = pd.Timestamp(value)
    return f"{ts.year}P{ts.month:02d}"


def normalize_period(value: Any, default_year: int = DATASET_YEAR) -> str:
    """
    Normalize many user/model supplied period formats to ``YYYYPMM``.

    Accepts ``2024P07``, ``2024-P07``, ``2024-07``, ``202407``, ``P07``,
    ``07``, ``7`` and plain integers.
    """
    if value is None:
        raise ValueError("period is required")

    raw = str(value).strip().upper().replace(" ", "").replace("-", "").replace("_", "")
    if not raw:
        raise ValueError("period is required")

    if raw.isdigit():
        digits = raw
        if len(digits) == 6:  # 202407
            return f"{digits[:4]}P{digits[4:6]}"
        if len(digits) <= 2:  # 7 / 07
            month = int(digits)
            if not 1 <= month <= 12:
                raise ValueError(f"Invalid month in period: {value!r}")
            return f"{default_year}P{month:02d}"
        raise ValueError(f"Unrecognized period format: {value!r}")

    if "P" in raw:
        head, _, tail = raw.partition("P")
        month = int(tail)
        year = int(head) if head else default_year
        if not 1 <= month <= 12:
            raise ValueError(f"Invalid month in period: {value!r}")
        return f"{year}P{month:02d}"

    raise ValueError(f"Unrecognized period format: {value!r}")


def is_closed_period(period: str, closed_periods: int, year: int = DATASET_YEAR) -> bool:
    """Return ``True`` when the payroll period is already closed for corrections."""
    month = int(normalize_period(period, default_year=year)[5:7])
    return month <= closed_periods


