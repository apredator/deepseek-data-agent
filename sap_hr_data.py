"""
Synthetic SAP HCM data layer.

Generates fully fictional tables that mimic the structure of real SAP HCM
infotypes and payroll results:

* ``PA0001_org``          - Organisational Assignment (Pernr, Orgeh, Kostl, Planstelle, Begda, Endda)
* ``PA0008_basic_pay``    - Basic Pay (Pernr, Lohnart, Betrag, Waehrung, Begda, Endda)
* ``PA0014_recurring``    - Recurring Payments/Deductions (Pernr, Lohnart, Betrag, Periodizitaet)
* ``RT_payroll_results``  - Payroll results (Pernr, Abrechnungsperiode, Lohnart, Betrag,
                             InPeriod / ForPeriod, Retro flag, Kostl)

The generator deliberately injects a known set of payroll anomalies and records
their exact location in an ``anomalies_manifest.json`` ground-truth file, so the
agent's findings can be scored objectively ("found N of M").

.. warning::
   **All data produced by this module is synthetic and fictional.** No real
   client, employee or payroll data is used anywhere in this project. Names are
   invented, amounts are random and the deliberate anomalies exist purely for
   demonstration.
"""

